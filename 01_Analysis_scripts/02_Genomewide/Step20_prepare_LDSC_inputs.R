# 第20步：八表型全基因组GWAS -> LDSC输入和可追溯质量控制。
# 使用第19步已验证环境；不联网安装；不运行遗传力/遗传相关分析。
(function() {
  base <- path.expand('~/胰腺')
  prior <- file.path(base,'19_LDSC_setup','LDSC_setup_1566e430f1187')
  if(!file.exists(file.path(prior,'completion_status.txt')) ||
     !any(readLines(file.path(prior,'completion_status.txt'),warn=FALSE)=='COMPLETED_SOFTWARE_AND_REFERENCES_READY'))
    stop('找不到已核验的第19步成功目录：',prior,'。请保留该目录原名。')
  cfg <- readRDS(file.path(prior,'LDSC_paths.rds'))
  if(!identical(cfg$source_commit,'6c673952cee74bd5c57aef1555a03b1c015399a0')) stop('第19步源码版本不一致。')
  if(!all(file.exists(c(cfg$python,cfg$ldsc,cfg$hapmap3_snplist)))) stop('第19步软件或参考路径不存在。')
  if(!requireNamespace('data.table',quietly=TRUE)) stop('缺少data.table。')
  registry <- data.frame(
    id=paste0('ebi-a-GCST',c('90016666','90016669','90016671','90016672','90016673','90016674','90016675','90016676')),
    trait=c('liver_volume','pancreas_volume','visceral_adipose_tissue_volume',
      'abdominal_subcutaneous_adipose_tissue_volume','liver_fat','liver_iron','pancreas_fat','pancreas_iron'),
    N=c(32860L,31758L,32860L,32860L,32858L,32858L,25617L,25617L),
    expected_records=rep(9263091L,8),stringsAsFactors=FALSE)
  paths <- file.path(base,paste0(registry$id,'.vcf.gz'))
  if(!all(file.exists(paths))) stop('缺少原始VCF：',paste(paths[!file.exists(paths)],collapse=', '))
  parent <- file.path(base,'20_LDSC_inputs')
  dir.create(parent,recursive=TRUE,showWarnings=FALSE)
  out <- tempfile('GWAS_inputs_',tmpdir=parent)
  if(!dir.create(out)) stop('无法建立结果目录。')
  report <- file.path(out,'reports');dir.create(report)
  writeLines('INCOMPLETE_CHECK_LOGS',file.path(report,'completion_status.txt'))
  data.table::fwrite(registry,file.path(report,'study_registry.tsv'),sep='\t')
  file.copy(file.path(prior,'LDSC_paths.tsv'),file.path(report,'LDSC_paths.tsv'))
  writeLines(capture.output(sessionInfo()),file.path(report,'R_sessionInfo.txt'))
  writeLines(c(
    'Step20: direct construction of LDSC SNP A1 A2 Z N format; no h2 or rg estimation.',
    'Z = VCF ES/SE. No reconstruction from rounded P values; no association-P threshold or LD clumping.',
    'Effect allele initially ALT. Output alleles follow HapMap3; signs are changed only by unambiguous allele matching.',
    'Keep autosomal biallelic SNVs, FILTER PASS or dot(unfiltered), valid ES/SE/LP/AF, GWAS MAF >=0.01.',
    'Exclude palindromic SNPs, incompatible alleles, and mismatched/missing reference positions.',
    'Predefined MHC exclusion: GRCh37 chr6:26000000-34000000 inclusive.',
    'Discard ALL occurrences of duplicated HapMap3 rsIDs observed anywhere in the source VCF, then duplicate positions.',
    'Study-level N is assumed for each retained SNP. It comes from the audited continuous-trait SAMPLE TotalControls field.',
    'No per-SNP SS or SI was observed in step18. This script rejects unexpected FORMAT changes.',
    'HapMap3 membership does NOT verify imputation INFO>0.9. Missing per-SNP sample sizes and INFO remain limitations.',
    'LP vs Z comparison is diagnostic only; discrepancies are flagged, never used to select associations.',
    'The output is read back by the fixed LDSC parser, and SNP/allele/Z/N values are checked.',
    'Summary mean Z2 and lambda GC are descriptive QC only, not heritability estimates.',
    'Review all QC flags before downstream h2/rg. Do not force rg intercept to zero for overlapping samples.',
    'Variant audit tables and sumstats stay on server. Upload 20_QC_review.zip.'),
    file.path(report,'analysis_rules_and_limitations.txt'))
  script <- file.path(base,'20_prepare_LDSC_inputs.R')
  if(file.exists(script)) file.copy(script,file.path(report,basename(script)))
  python_lines <- c(
"\"\"\"Step 20: audited direct LDSC sumstats; Z=ES/SE, signed to HapMap3 A1.\"\"\"",
"import sys, os, re, gzip, json, hashlib, traceback, zipfile, gc",
"from pathlib import Path",
"from collections import Counter",
"import numpy as np",
"import pandas as pd",
"from scipy.special import log_ndtr",
"",
"COLS = ['CHR','BP','SNP','REF','ALT','QUAL','FILTER','INFO','FORMAT','VALUE']",
"COMPLEMENT = {'A':'T','T':'A','C':'G','G':'C'}",
"STAGES = ['raw_records','autosomal_SNV','filter_PASS_or_unfiltered',",
"          'HapMap3_membership','valid_ES_SE_LP_AF','MAF_ge_001',",
"          'nonpalindromic','alleles_compatible','LD_reference_position_match',",
"          'outside_MHC_26_34Mb','unique_rsid','unique_position','final']",
"",
"def sha(path):",
"    h=hashlib.sha256()",
"    with open(path,'rb') as f:",
"        for b in iter(lambda:f.read(2**20),b''): h.update(b)",
"    return h.hexdigest()",
"",
"def table(rows,path):",
"    pd.DataFrame(rows).to_csv(path,sep='\\t',index=False)",
"",
"def get_header(f,study):",
"    lines=[]",
"    while True:",
"        line=f.readline()",
"        if not line: raise ValueError('VCF header missing')",
"        lines.append(line.rstrip('\\n'))",
"        if line.startswith('#CHROM\\t'):",
"            fields=line.strip().split('\\t')",
"            if len(fields)!=10 or fields[-1]!=study['id']: raise ValueError('Wrong VCF sample ID/columns')",
"            break",
"        if not line.startswith('#'): raise ValueError('Records before VCF header')",
"    sample=[s for s in lines if s.startswith('##SAMPLE=<')]",
"    if len(sample)!=1: raise ValueError('Expected one SAMPLE header')",
"    meta=dict(re.findall(r'(\\w+)=([^,>]+)',sample[0].split('<',1)[1]))",
"    if meta.get('ID')!=study['id'] or meta.get('StudyType')!='Continuous': raise ValueError('Wrong SAMPLE metadata')",
"    if float(meta['TotalControls'])!=study['N']: raise ValueError('Study N differs from step18')",
"    if int(meta['HarmonisedVariants'])!=study['expected_records']: raise ValueError('Variant count differs from step18')",
"    if not any('assembly=HG19/GRCh37' in s for s in lines): raise ValueError('GRCh37 header not confirmed')",
"    return lines",
"",
"def align(a,b,h1,h2):",
"    ca=a.map(COMPLEMENT);cb=b.map(COMPLEMENT)",
"    direct=(a==h1)&(b==h2);swap=(a==h2)&(b==h1)",
"    strand=(ca==h1)&(cb==h2);strand_swap=(ca==h2)&(cb==h1)",
"    op=np.select([direct,swap,strand,strand_swap],['direct','swap','strand','strand_swap'],default='incompatible')",
"    sign=np.select([direct|strand,swap|strand_swap],[1,-1],default=0)",
"    return op,sign",
"",
"def convert(study,hm,ref,base,out,chunk_size=100000):",
"    sid=study['id'];path=base/(sid+'.vcf.gz');report=out/'reports'",
"    before=path.stat();digest=sha(path)",
"    counts=Counter({x:0 for x in STAGES});formats=Counter();all_hm_ids=Counter();parts=[]",
"    print('\\nProcessing',sid,study['trait'],flush=True)",
"    with gzip.open(path,'rt') as f:",
"        header=get_header(f,study)",
"        (report/(sid+'_header.txt')).write_text('\\n'.join(header)+'\\n',encoding='utf-8')",
"        reader=pd.read_csv(f,sep='\\t',names=COLS,header=None,dtype=str,",
"                           keep_default_na=False,chunksize=chunk_size)",
"        for block,d in enumerate(reader,1):",
"            if d.isna().any().any() or (d=='').any().any(): raise ValueError('Missing VCF columns/empty fields')",
"            if not isinstance(d.index,pd.RangeIndex): raise ValueError('Unexpected VCF field count/index')",
"            counts['raw_records']+=len(d)",
"            formats.update(d.FORMAT.value_counts().to_dict())",
"            if not d.FORMAT.isin(['ES:SE:LP:AF:ID','ES:SE:LP:AF']).all():",
"                raise ValueError('FORMAT differs from step18 audit; stop rather than assume SS/SI absent')",
"            # Count duplicate HapMap3 rsIDs BEFORE any biological/quality filter.",
"            all_hm_ids.update(d.loc[d.SNP.isin(hm.index),'SNP'])",
"            d=d.loc[d.CHR.isin([str(i) for i in range(1,23)]) & d.REF.isin(list('ACGT')) &",
"                    d.ALT.isin(list('ACGT')) & (d.REF!=d.ALT)].copy()",
"            counts['autosomal_SNV']+=len(d)",
"            d=d.loc[d.FILTER.isin(['PASS','.'])].copy();counts['filter_PASS_or_unfiltered']+=len(d)",
"            d=d.loc[d.SNP.isin(hm.index)].copy();counts['HapMap3_membership']+=len(d)",
"            if len(d):",
"                for fmt,g in d.groupby('FORMAT',sort=False):",
"                    if not (g.VALUE.str.count(':')==len(fmt.split(':'))-1).all(): raise ValueError('Malformed FORMAT values')",
"                v=d.VALUE.str.split(':',expand=True)",
"                for key,j in [('BETA',0),('SE',1),('LP',2),('AF',3)]: d[key]=pd.to_numeric(v[j],errors='coerce')",
"                d['BP']=pd.to_numeric(d.BP,errors='coerce')",
"                if not (np.isfinite(d.BP)&(d.BP>0)&(d.BP==np.floor(d.BP))).all(): raise ValueError('Invalid position')",
"                d['BP']=d.BP.astype(int);d['CHR']=d.CHR.astype(int)",
"                valid=np.isfinite(d[['BETA','SE','LP','AF']]).all(axis=1)&(d.SE>0)&(d.LP>=0)&d.AF.between(0,1)",
"                d=d.loc[valid].copy();counts['valid_ES_SE_LP_AF']+=len(d)",
"                d['MAF']=np.minimum(d.AF,1-d.AF)",
"                d=d.loc[d.MAF>=0.01].copy();counts['MAF_ge_001']+=len(d)",
"                d=d.loc[~(d.REF+d.ALT).isin(['AT','TA','CG','GC'])].copy();counts['nonpalindromic']+=len(d)",
"                d=d.join(hm,on='SNP')",
"                d['operation'],d['sign']=align(d.ALT,d.REF,d.A1,d.A2)",
"                d=d.loc[d.sign!=0].copy();counts['alleles_compatible']+=len(d)",
"                d=d.join(ref,on='SNP')",
"                d=d.loc[(d.CHR==d.REF_CHR)&(d.BP==d.REF_BP)].copy();counts['LD_reference_position_match']+=len(d)",
"                d=d.loc[~((d.CHR==6)&d.BP.between(26000000,34000000))].copy();counts['outside_MHC_26_34Mb']+=len(d)",
"                if len(d):",
"                    d['Z_ALT']=d.BETA/d.SE;d['Z']=d.Z_ALT*d.sign",
"                    if not np.isfinite(d.Z).all(): raise ValueError('Nonfinite ES/SE')",
"                    d['AF_A1']=np.where(d.sign==1,d.AF,1-d.AF)",
"                    d['N']=study['N']",
"                    parts.append(d[['SNP','CHR','BP','REF','ALT','A1','A2','BETA','SE','LP','AF','MAF','AF_A1','operation','sign','Z_ALT','Z','N']])",
"            if block%10==0: print(sid,'records read:',counts['raw_records'],flush=True)",
"    if counts['raw_records']!=study['expected_records']: raise ValueError('Read count differs from VCF header/step18')",
"    if not parts: raise ValueError('No eligible HapMap3 variants')",
"    x=pd.concat(parts,ignore_index=True);del parts",
"    dupids={k for k,n in all_hm_ids.items() if n>1}",
"    table([{'SNP':k,'VCF_records':all_hm_ids[k]} for k in sorted(dupids)],report/(sid+'_duplicate_rsid.tsv'))",
"    x=x.loc[~x.SNP.isin(dupids)].copy();counts['unique_rsid']=len(x)",
"    duppos=x.duplicated(['CHR','BP'],keep=False)",
"    x.loc[duppos,['SNP','CHR','BP','REF','ALT']].to_csv(report/(sid+'_duplicate_position.tsv'),sep='\\t',index=False)",
"    x=x.loc[~duppos].sort_values(['CHR','BP','SNP']).reset_index(drop=True)",
"    counts['unique_position']=len(x);counts['final']=len(x)",
"    if len(x)==0: raise ValueError('No variants after duplicate QC')",
"    if not x.SNP.is_unique: raise ValueError('Duplicate output SNPs')",
"    # LP consistency is descriptive; do not select on association strength.",
"    x['LP_from_Z']=-(np.log(2.0)+log_ndtr(-np.abs(x.Z)))/np.log(10.0)",
"    delta=np.abs(x.LP_from_Z-x.LP)",
"    x['LP_difference_flag']=delta>np.maximum(0.1,0.01*x.LP)",
"    x.loc[x.LP_difference_flag,['SNP','LP','LP_from_Z','Z']].head(100).to_csv(report/(sid+'_LP_discrepancy_examples.tsv'),sep='\\t',index=False)",
"    x.to_csv(out/'variant_audit'/(sid+'_retained.tsv.gz'),sep='\\t',index=False,compression='gzip',float_format='%.12g')",
"    target=out/'sumstats'/(sid+'.sumstats.gz')",
"    x[['SNP','A1','A2','Z','N']].to_csv(target,sep='\\t',index=False,compression='gzip',float_format='%.12g')",
"    # Read with the exact LDSC parser installed in step19, then verify Z/sign/N.",
"    import ldscore.parse as lp",
"    readback=lp.sumstats(str(target),alleles=True,dropna=False)",
"    if len(readback)!=len(x) or readback.isna().any().any(): raise ValueError('LDSC readback lost rows or found NA')",
"    if not np.array_equal(readback.SNP.to_numpy(),x.SNP.to_numpy()): raise ValueError('SNP readback mismatch')",
"    if not np.allclose(readback.Z,x.Z,rtol=1e-10,atol=1e-12): raise ValueError('Z/sign readback mismatch')",
"    if not (readback.N==study['N']).all(): raise ValueError('N mismatch')",
"    for a in ['A1','A2']:",
"        if not np.array_equal(readback[a],x[a]): raise ValueError('Allele mismatch')",
"    stat=path.stat()",
"    if stat.st_size!=before.st_size or stat.st_mtime_ns!=before.st_mtime_ns: raise ValueError('Input changed while processing')",
"    table([{'stage':k,'n_remaining':counts[k]} for k in STAGES],report/(sid+'_QC_flow.tsv'))",
"    table([{'FORMAT':k,'records':n} for k,n in formats.items()],report/(sid+'_FORMAT_counts.tsv'))",
"    table([{'operation':k,'n':n} for k,n in x.operation.value_counts().items()],report/(sid+'_allele_operations.tsv'))",
"    x.groupby('CHR').size().rename('n').reset_index().to_csv(report/(sid+'_chromosome_counts.tsv'),sep='\\t',index=False)",
"    row=dict(id=sid,trait=study['trait'],N=study['N'],N_source='study_level_assumption_from_VCF_TotalControls',",
"             n_raw=counts['raw_records'],n_final=len(x),SS_available=False,SI_available=False,",
"             n_LP_discrepancy_flags=int(x.LP_difference_flag.sum()),max_LP_difference=float(delta.max()),",
"             mean_Z2=float(np.mean(x.Z**2)),median_Z=float(x.Z.median()),",
"             lambda_GC=float(np.median(x.Z**2)/0.4549364231195727),",
"             n_chromosomes=int(x.CHR.nunique()),LDSC_parser='PASS',",
"             status='PASS_INPUT_QC' if len(x)>=200000 and x.CHR.nunique()==22 and not x.LP_difference_flag.any() else 'REVIEW_REQUIRED',",
"             sumstats=str(target),sumstats_sha256=sha(target),VCF_sha256=digest)",
"    table([row],report/(sid+'_summary.tsv'))",
"    print(sid,'DONE; retained:',len(x),'status:',row['status'],flush=True)",
"    ids=set(x.SNP);del x,readback;gc.collect()",
"    return row,ids",
"",
"def main():",
"    base=Path(sys.argv[1]);out=Path(sys.argv[2]);config=Path(sys.argv[3]);registry=Path(sys.argv[4])",
"    cfg=pd.read_csv(config,sep='\\t').set_index('item').value.to_dict()",
"    studies=pd.read_csv(registry,sep='\\t').to_dict('records')",
"    for n in ['reports','sumstats','variant_audit']: (out/n).mkdir(exist_ok=True)",
"    report=out/'reports'",
"    prior=Path(sys.argv[5])",
"    # Verify the software and reference files against the successful step19 manifest.",
"    records=[]",
"    refs_qc=pd.read_csv(prior/'reference_file_checksums.tsv',sep='\\t')",
"    for rr in refs_qc.to_dict('records'):",
"        p=Path(rr['path']);ok=p.is_file() and sha(p)==rr['sha256']",
"        records.append(dict(kind='reference',path=str(p),match=ok))",
"        if not ok: raise ValueError('Step19 reference checksum changed: '+str(p))",
"    src_qc=pd.read_csv(prior/'source_code_checksums.tsv',sep='\\t')",
"    for rr in src_qc.to_dict('records'):",
"        p=Path(rr['path']);ok=p.is_file() and hashlib.md5(p.read_bytes()).hexdigest()==rr['md5']",
"        records.append(dict(kind='source',path=str(p),match=ok))",
"        if not ok: raise ValueError('Step19 source checksum changed: '+str(p))",
"    table(records,report/'step19_resource_recheck.tsv')",
"    sys.path.insert(0,str(Path(cfg['ldsc']).parent))",
"    hm=pd.read_csv(cfg['hapmap3_snplist'],sep=r'\\s+',dtype=str)",
"    if list(hm.columns)!=['SNP','A1','A2'] or not hm.SNP.is_unique or hm.isna().any().any(): raise ValueError('HapMap3 invalid')",
"    if not hm.A1.isin(list('ACGT')).all() or not hm.A2.isin(list('ACGT')).all(): raise ValueError('HapMap3 invalid alleles')",
"    hm=hm.set_index('SNP')",
"    refs=[]",
"    for ch in range(1,23):",
"        r=pd.read_csv(cfg['reference_ld_chr']+str(ch)+'.l2.ldscore.gz',sep=r'\\s+',usecols=['SNP','CHR','BP'])",
"        if not (r.CHR==ch).all(): raise ValueError('Reference chromosome mismatch')",
"        refs.append(r)",
"    ref=pd.concat(refs,ignore_index=True)",
"    if not ref.SNP.is_unique: raise ValueError('Duplicate reference rsIDs')",
"    ref=ref.rename(columns={'CHR':'REF_CHR','BP':'REF_BP'}).set_index('SNP');del refs",
"    rows=[];sets={}",
"    for study in studies:",
"        row,ids=convert(study,hm,ref,base,out)",
"        rows.append(row);sets[study['id']]=ids",
"        table(rows,report/'GWAS_LDSC_QC_summary.tsv')",
"    pair=[]",
"    for i,a in enumerate(studies):",
"        for b in studies[i+1:]:",
"            n=len(sets[a['id']]&sets[b['id']])",
"            pair.append(dict(trait1=a['trait'],trait2=b['trait'],n_common=n,flag='REVIEW_LT_200K' if n<200000 else 'OK'))",
"    table(pair,report/'pairwise_SNP_overlap.tsv')",
"    table(studies,report/'study_registry.tsv')",
"    all_common=len(set.intersection(*sets.values()))",
"    (report/'all_trait_common_SNP_count.txt').write_text(str(all_common)+'\\n')",
"    (report/'completion_status.txt').write_text('COMPLETED_INPUT_PREPARATION_REVIEW_QC_BEFORE_LDSC\\n')",
"    print('\\nALL EIGHT INPUTS PREPARED. All-trait SNP intersection:',all_common,flush=True)",
"",
"if __name__=='__main__':",
"    out=Path(sys.argv[2]);(out/'reports').mkdir(exist_ok=True)",
"    try: main()",
"    except Exception:",
"        (out/'reports'/'completion_status.txt').write_text('INCOMPLETE_CHECK_LOGS\\n')",
"        (out/'reports'/'python_error.txt').write_text(traceback.format_exc())",
"        raise",
"    finally:",
"        # Small review bundle; large per-variant and sumstats files stay on server.",
"        with zipfile.ZipFile(out/'20_QC_review.zip','w',zipfile.ZIP_DEFLATED) as z:",
"            for p in sorted((out/'reports').glob('*')):",
"                if p.is_file(): z.write(p,'reports/'+p.name)"
)
  helper <- file.path(out,'prepare_ldsc.py')
  writeLines(python_lines,helper,useBytes=TRUE)
  log <- file.path(report,'python_console.txt')
  cat('结果目录：',out,'\n')
  cat('将顺序处理8份VCF。进度日志：',log,'\n')
  cat('运行中控制台可能暂时不刷新；可在Files中打开python_console.txt查看进度。\n')
  flush.console()
  run_error <- NULL
  rc <- tryCatch(system2(cfg$python,
    args=vapply(c('-u',helper,base,out,file.path(report,'LDSC_paths.tsv'),
                  file.path(report,'study_registry.tsv'),prior),shQuote,character(1)),
    stdout=log,stderr=log,
    env=c('PYTHONNOUSERSITE=1','PYTHONPATH=','OPENBLAS_NUM_THREADS=1','OMP_NUM_THREADS=1','MKL_NUM_THREADS=1')),
    error=function(e) {run_error <<- conditionMessage(e);127L})
  if(!is.null(run_error)) writeLines(run_error,file.path(report,'R_error.txt'))
  # Python退出后重新打包，将完整末尾日志也纳入；不打包大体积逐变异文件。
  pack <- paste('import sys,zipfile,pathlib;',
    'o=pathlib.Path(sys.argv[1]);',
    'z=zipfile.ZipFile(o/"20_QC_review.zip","w",zipfile.ZIP_DEFLATED);',
    '[z.write(p,"reports/"+p.name) for p in sorted((o/"reports").glob("*")) if p.is_file()];z.close()')
  pack_rc <- tryCatch(system2(cfg$python,
    args=vapply(c('-c',pack,out),shQuote,character(1)),stdout=TRUE,stderr=TRUE),error=function(e) conditionMessage(e))
  if(rc!=0L) {
    if(file.exists(log)) cat(tail(readLines(log,warn=FALSE),25L),sep='\n')
    stop('第20步未完成。请上传结果目录中的20_QC_review.zip；若无ZIP则上传reports文件夹。')
  }
  status <- readLines(file.path(report,'completion_status.txt'),warn=FALSE)
  if(!identical(status,'COMPLETED_INPUT_PREPARATION_REVIEW_QC_BEFORE_LDSC')) stop('完成标记不正确，请上传核查ZIP。')
  summary <- data.table::fread(file.path(report,'GWAS_LDSC_QC_summary.tsv'))
  cat('\n===== 第20步输入准备完成 =====\n')
  print(summary[,c('id','trait','N','n_final','n_LP_discrepancy_flags','LDSC_parser','status'),with=FALSE])
  cat('\n请上传：',file.path(out,'20_QC_review.zip'),'\n')
  cat('本步尚未估计遗传力或遗传相关性。存在REVIEW_REQUIRED时先核查，不直接进入下一步。\n')
})()
